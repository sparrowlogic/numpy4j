    private static final float TOL = 0.001f;
    private static final float TOL_MULTI = 0.05f;
    private static final java.util.Set<String> MULTI_LAYER = java.util.Set.of(
            "qr_reconstruct", "svd_reconstruct", "eigvals", "pinv_reconstruct",
            "eigh_eigenvalues", "cond", "lstsq", "cross_entropy", "layer_norm",
            "geomspace", "logspace"
    );
    private static Map<String, float[]> REF;

    @BeforeAll
    static void loadReference() throws IOException {
        Path path = Path.of("tools/reference_values.json");
        if (!Files.exists(path)) {
            // CI may generate it; skip if missing
            REF = Map.of();
            return;
        }
        String json = Files.readString(path);
        REF = parseJson(json);
    }

    @TestFactory
    Collection<DynamicTest> parityTests() {
        if (REF.isEmpty()) {
            return List.of(DynamicTest.dynamicTest("skip: reference_values.json not found", () -> {}));
        }

        List<DynamicTest> tests = new ArrayList<>();
        try (var arena = Arena.ofConfined()) {
            Map<String, float[]> actual = computeActual(arena);
            for (var entry : REF.entrySet()) {
                String name = entry.getKey();
                float[] expected = entry.getValue();
                float[] got = actual.get(name);
                tests.add(DynamicTest.dynamicTest("parity:" + name, () -> {
                    if (got == null) {
                        fail("No numpy4j output for: " + name);
                    }
                    int len = Math.min(expected.length, got.length);
                    float tol = MULTI_LAYER.contains(name) ? TOL_MULTI : TOL;
                    for (int i = 0; i < len; i++) {
                        assertEquals(expected[i], got[i], tol,
                                name + "[" + i + "] numpy=" + expected[i] + " java=" + got[i]);
                    }
                }));
            }
        }
        return tests;
    }

