/**
 * Mathematical parity validation: compares numpy4j output against NumPy reference values.
 *
 * Reference values are generated by tools/validate_against_reference.py and stored in
 * tools/reference_values.json. Each key maps to a numpy function, each value is the
 * first N output values as floats.
 *
 * Pinned to numpy commit: 4a126b31f5d1c03d4cea052abc49d31b8667cff3
 */
