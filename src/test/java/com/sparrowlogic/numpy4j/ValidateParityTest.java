    private static float[] toF32(NdArray a) {
        double[] d = a.toDoubleArray();
        float[] f = new float[d.length];
        for (int i = 0; i < d.length; i++) f[i] = (float) d[i];
        return f;
    }

    /** Minimal JSON parser for flat {key: [numbers]} structure. */
    private static Map<String, float[]> parseJson(String json) {
        Map<String, float[]> map = new LinkedHashMap<>();
        Pattern keyPattern = Pattern.compile("\"([^\"]+)\"\\s*:\\s*\\[([^\\]]*)]");
        Matcher matcher = keyPattern.matcher(json);
        while (matcher.find()) {
            String key = matcher.group(1);
            if (key.startsWith("_")) continue;
            String[] vals = matcher.group(2).split(",");
            float[] arr = new float[vals.length];
            for (int i = 0; i < vals.length; i++) {
                arr[i] = Float.parseFloat(vals[i].trim());
            }
            map.put(key, arr);
        }
        return map;
    }
